# ----------------------- helper funcs ----------------------- #

def fetch_data(ticker, start, end):
    """Fetch historical OHLC data from Yahoo via pandas_datareader."""
    print(f"Fetching {ticker} from {start} to {end} ...")
    df = yf.download(ticker, start=start, end=end)
    df = df[['Close']].rename(columns={'Close': 'close'}).reset_index()
    return df

def plot_series(df, ticker, out='price_plot.png'):
    plt.figure(figsize=(10,5))
